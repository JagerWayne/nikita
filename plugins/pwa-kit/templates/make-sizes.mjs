// Writes js/boot/sizes.js (byte size of every file in APP_FILES) for the update progress bar.
// Run after the last file change of a release:  node tools/make-sizes.mjs
import { readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const self = {};
new Function('self', readFileSync(join(root, 'js/boot/files.js'), 'utf8'))(self);
const files = self.APP_FILES || [];
const sizes = {};
const missing = [];
for (const f of files) {
  const p = join(root, f);
  if (f === 'js/boot/sizes.js') continue;           // its own size is unknowable (and tiny); the worker falls back to a guess
  if (!existsSync(p)) { missing.push(f); continue; }
  sizes[f] = statSync(p).size;
}
if (missing.length) { console.error('Listed in APP_FILES but missing on disk:\n  ' + missing.join('\n  ')); process.exit(1); }
const body = '/* Generated by tools/make-sizes.mjs: raw byte size of each file in APP_FILES (used by the update progress bar). */\n' +
  'self.APP_SIZES = ' + JSON.stringify(sizes, null, 1) + ';\n';
writeFileSync(join(root, 'js/boot/sizes.js'), body);
console.log('sizes.js written: ' + files.length + ' files, ' + Object.values(sizes).reduce((a, b) => a + b, 0) + ' bytes');
